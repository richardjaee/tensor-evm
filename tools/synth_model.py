#!/usr/bin/env python3
"""Build a tiny Qwen3-shaped model and the tokens float64 says it emits.

The real checkpoint is 1.2 GB, so the examples that run it cannot live in CI, and this
project has already been caught once by a change that broke every example while the test
suite stayed green. Examples only run when something runs them.

This produces a model small enough to commit — a few hundred kilobytes — with every
structural feature that has caused a bug here:

  * `head_dim` independent of `dim / n_heads`, so the query and output projections are not
    square, which is what Qwen3 does and what the companion project's exporter assumes away
  * grouped-query attention, so several query heads share one key/value head
  * per-layer norm weights, which were quietly shared across layers once and produced a
    fluent model that was not the one published
  * norm weights far above unit scale, which broke three separate activation bounds
  * several positions, so the causal mask and the key/value cache are exercised rather than
    trivially satisfied at position zero

Weights are pseudo-random but deterministic, so a failure is reproducible from the seed
alone and the fixture can be regenerated byte for byte.
"""

import argparse
import json
import os
import sys

import numpy as np

from quantize import blob, quantize_rows

Q32 = 1 << 32


def to_q32(a):
    return np.rint(np.asarray(a, dtype=np.float64) * Q32).astype(np.int64)


def rmsnorm(x, w, eps):
    return x / np.sqrt((x * x).mean() + eps) * w


def softmax(x):
    e = np.exp(x - x.max())
    return e / e.sum()


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", required=True)
    ap.add_argument("--seed", type=int, default=11)
    ap.add_argument("--dim", type=int, default=32)
    ap.add_argument("--hidden", type=int, default=64)
    ap.add_argument("--layers", type=int, default=4)
    ap.add_argument("--heads", type=int, default=4)
    ap.add_argument("--kv", type=int, default=2)
    ap.add_argument("--head-dim", type=int, default=16)
    ap.add_argument("--vocab", type=int, default=128)
    ap.add_argument("--positions", type=int, default=3)
    a = ap.parse_args()

    dim, hidden, L, H, KV, hs = a.dim, a.hidden, a.layers, a.heads, a.kv, a.head_dim
    V, P = a.vocab, a.positions
    eps = 1e-6
    theta = 1e6
    half = hs // 2
    group = H // KV
    qw, kvw = H * hs, KV * hs

    assert hs * H != dim, "head_dim*heads must differ from dim, or the shape is not Qwen3's"
    assert H % KV == 0, "query heads must group evenly onto key/value heads"

    rng = np.random.default_rng(a.seed)
    os.makedirs(a.out, exist_ok=True)

    def write(name, data):
        with open(os.path.join(a.out, name), "wb") as f:
            f.write(data)

    def mat(rows, cols):
        return rng.normal(0.0, 0.08, size=(rows, cols))

    # Norm weights deliberately far from unit scale, growing with depth as Qwen3's do. Every
    # activation bound this project imposed was set by looking at shallow layers.
    def norm(n, scale):
        return np.abs(rng.normal(1.0, 0.3, size=n)) * scale

    W = []
    for l in range(L):
        W.append(
            {
                "q": mat(qw, dim),
                "k": mat(kvw, dim),
                "v": mat(kvw, dim),
                "o": mat(dim, qw),
                "gate": mat(hidden, dim),
                "up": mat(hidden, dim),
                "down": mat(dim, hidden),
                "input_norm": norm(dim, 1.0 + 6.0 * l / max(L - 1, 1)),
                "q_norm": norm(hs, 3.0),
                "k_norm": norm(hs, 12.0),
                "post_norm": norm(dim, 1.0 + 20.0 * l / max(L - 1, 1)),
            }
        )
    final_norm = norm(dim, 2.0)
    head = mat(V, dim)
    emb = rng.normal(0.0, 0.05, size=(V, dim))
    ids = [int(rng.integers(0, V)) for _ in range(P)]

    # ---- export, in the layout the chain reads ----
    for l in range(L):
        for key in ("q", "k", "v", "o", "gate", "up", "down"):
            qm, sh = quantize_rows(W[l][key].astype(np.float32))
            write(f"l{l}_{key}.bin", blob(qm, sh))
        for key in ("input_norm", "q_norm", "k_norm", "post_norm"):
            write(f"l{l}_{key}.bin", to_q32(W[l][key]).astype("<i8").tobytes())

    write("final_norm.bin", to_q32(final_norm).astype("<i8").tobytes())
    qm, sh = quantize_rows(head.astype(np.float32))
    write("lm_head.bin", blob(qm, sh))
    write("embed.bin", to_q32(emb[ids].reshape(-1)).astype("<i8").tobytes())

    inv = theta ** (-np.arange(0, half, dtype=np.float64) * 2.0 / hs)
    ang = np.arange(P, dtype=np.float64)[:, None] * inv[None, :]
    cos, sin = np.cos(ang), np.sin(ang)
    write("cos.bin", to_q32(cos.reshape(-1)).astype("<i8").tobytes())
    write("sin.bin", to_q32(sin.reshape(-1)).astype("<i8").tobytes())

    # ---- float64 reference ----
    kc = [[] for _ in range(L)]
    vc = [[] for _ in range(L)]
    tokens = []
    peak = 0.0
    for p in range(P):
        x = emb[ids[p]].copy()
        for l in range(L):
            w = W[l]
            h = x.copy()
            n = rmsnorm(h, w["input_norm"], eps)
            q, k, v = w["q"] @ n, w["k"] @ n, w["v"] @ n
            for i in range(H):
                s = slice(i * hs, (i + 1) * hs)
                q[s] = rmsnorm(q[s], w["q_norm"], eps)
                a_, b_ = q[s][:half].copy(), q[s][half:].copy()
                q[s] = np.concatenate([a_ * cos[p] - b_ * sin[p], a_ * sin[p] + b_ * cos[p]])
            for i in range(KV):
                s = slice(i * hs, (i + 1) * hs)
                k[s] = rmsnorm(k[s], w["k_norm"], eps)
                a_, b_ = k[s][:half].copy(), k[s][half:].copy()
                k[s] = np.concatenate([a_ * cos[p] - b_ * sin[p], a_ * sin[p] + b_ * cos[p]])
            kc[l].append(k)
            vc[l].append(v)

            attn = np.zeros(qw)
            for i in range(H):
                kvh = i // group
                qi = q[i * hs : (i + 1) * hs]
                sc = np.array(
                    [qi @ kc[l][t][kvh * hs : (kvh + 1) * hs] / np.sqrt(hs) for t in range(p + 1)]
                )
                pr = softmax(sc)
                for t in range(p + 1):
                    attn[i * hs : (i + 1) * hs] += pr[t] * vc[l][t][kvh * hs : (kvh + 1) * hs]

            h = h + w["o"] @ attn
            n = rmsnorm(h, w["post_norm"], eps)
            gt, up = w["gate"] @ n, w["up"] @ n
            h = h + w["down"] @ ((gt / (1.0 + np.exp(-gt))) * up)
            x = h
            peak = max(peak, float(np.abs(x).max()))
        tokens.append(int(np.argmax(head @ rmsnorm(x, final_norm, eps))))

    write("tokens.bin", np.asarray(tokens, dtype="<u4").tobytes())
    meta = {
        "dim": dim, "hidden": hidden, "n_layers": L, "n_heads": H, "n_kv": KV,
        "head_dim": hs, "vocab": V, "positions": P, "rope_theta": theta,
        "prompt_ids": ids, "seed": a.seed,
    }
    with open(os.path.join(a.out, "meta.json"), "w") as f:
        json.dump(meta, f, indent=2)

    total = sum(os.path.getsize(os.path.join(a.out, f)) for f in os.listdir(a.out))
    print(f"dim {dim}, hidden {hidden}, layers {L}, heads {H}, kv {KV}, head_dim {hs}, vocab {V}")
    print(f"  q_proj {qw}x{dim}, o_proj {dim}x{qw} — neither square")
    print(f"  peak residual magnitude {peak:.1f}")
    print(f"  tokens {tokens}")
    print(f"  wrote {a.out} ({total/1024:.0f} KB)")


if __name__ == "__main__":
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    sys.exit(main())
