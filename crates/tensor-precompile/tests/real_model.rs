//! Real Qwen3-0.6B weights, through the whole stack, against float64 truth.
//!
//! Everything before this checked integer code against integer code. That proves the
//! precompile and the kernel agree; it cannot prove either is right, because they share an
//! implementation. This runs slices of an actual published checkpoint and compares against
//! what the model means — the same projection in float64 from the original bf16 weights.
//!
//! The distinction earned its place. An earlier version of the kernel requantised by
//! `32 - shift` instead of `shift`. Every integer test passed, because the reference vector
//! generator made the identical mistake; the two agreed with each other and disagreed with
//! the model by more than a thousand percent. Only float64 exposed it.
//!
//! Fixtures are leading-row slices of real tensors, small enough to commit, so the test
//! does not depend on a 1.5 GB checkpoint being present.

use revm::context::{Context, TxEnv};
use revm::context_interface::result::{ExecutionResult, Output};
use revm::database::{CacheDB, EmptyDB};
use revm::primitives::{keccak256, Address, Bytes, TxKind, U256};
use revm::state::{AccountInfo, Bytecode};
use revm::{DatabaseCommit, ExecuteEvm, MainBuilder, MainContext};
use std::path::{Path, PathBuf};
use std::process::Command;
use tensor_precompile::state::TensorPrecompiles;

const CALLER: Address = Address::new([0x11; 20]);
const REGISTRY: Address = Address::new([0x55; 20]);
const WEIGHTS: Address = Address::new([0x33; 20]);
const MODEL_ID: u64 = 1;

/// Activations are Q32: `v` is stored as `round(v * 2^32)`.
const Q32: f64 = 4_294_967_296.0;

fn repo_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(|p| p.parent())
        .expect("workspace root")
        .to_path_buf()
}

/// A fixture: real weights in the precompile's format, real activations, and both the
/// integer answer and the float64 answer they should produce.
struct Fixture {
    name: String,
    rows: u32,
    cols: u32,
    blob: Vec<u8>,
    activations: Vec<i64>,
    expected: Vec<i64>,
    float_reference: Vec<f64>,
}

/// Minimal JSON reading, rather than a dependency.
///
/// The fixtures are generated by a script in this repository and have a fixed shape, so a
/// full parser would buy nothing. Anything unexpected panics, which in a test is the
/// correct response to a malformed input.
fn field<'a>(json: &'a str, key: &str) -> &'a str {
    let at = json
        .find(&format!("\"{key}\":"))
        .unwrap_or_else(|| panic!("fixture missing key {key}"));
    &json[at + key.len() + 3..]
}

fn number(json: &str, key: &str) -> i64 {
    field(json, key)
        .split([',', '}'])
        .next()
        .expect("value")
        .trim()
        .parse()
        .unwrap_or_else(|e| panic!("key {key} is not an integer: {e}"))
}

fn array<T: std::str::FromStr>(json: &str, key: &str) -> Vec<T>
where
    T::Err: std::fmt::Debug,
{
    let rest = field(json, key);
    let open = rest.find('[').expect("array start");
    let close = rest.find(']').expect("array end");
    rest[open + 1..close]
        .split(',')
        .map(|s| s.trim().parse::<T>().expect("array element"))
        .collect()
}

fn load(name: &str) -> Fixture {
    let dir = repo_root().join("testdata");
    let json = std::fs::read_to_string(dir.join(format!("{name}.json")))
        .unwrap_or_else(|e| panic!("fixture {name}.json: {e}"));
    let blob = std::fs::read(dir.join(format!("{name}.bin")))
        .unwrap_or_else(|e| panic!("fixture {name}.bin: {e}"));

    let rows = number(&json, "rows") as u32;
    let cols = number(&json, "cols") as u32;
    let activations: Vec<i64> = array(&json, "activations");
    let expected: Vec<i64> = array(&json, "expected");
    let float_reference: Vec<f64> = array(&json, "float_reference");

    assert_eq!(activations.len(), cols as usize, "{name}: activation width");
    assert_eq!(expected.len(), rows as usize, "{name}: expected length");
    assert_eq!(
        blob.len(),
        rows as usize + rows as usize * cols as usize * 2,
        "{name}: blob size does not match the declared shape"
    );

    Fixture {
        name: name.to_string(),
        rows,
        cols,
        blob,
        activations,
        expected,
        float_reference,
    }
}

fn runtime_code() -> Vec<u8> {
    let src = repo_root().join("contracts/src/ModelRegistry.sol");
    let out = Command::new("solc")
        .args(["--optimize", "--optimize-runs", "200", "--bin-runtime"])
        .arg(&src)
        .output()
        .expect("solc must be installed to run this test");
    assert!(
        out.status.success(),
        "solc failed: {}",
        String::from_utf8_lossy(&out.stderr)
    );
    let text = String::from_utf8(out.stdout).expect("utf8");
    let at = text
        .find(":ModelRegistry =======")
        .expect("ModelRegistry section");
    let hex = text[at..]
        .lines()
        .find(|l| l.starts_with("60"))
        .expect("runtime bytecode")
        .trim();
    (0..hex.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&hex[i..i + 2], 16).expect("hex"))
        .collect()
}

fn selector(sig: &str) -> [u8; 4] {
    let h = keccak256(sig.as_bytes());
    [h[0], h[1], h[2], h[3]]
}

fn word(v: u64) -> [u8; 32] {
    let mut w = [0u8; 32];
    w[24..].copy_from_slice(&v.to_be_bytes());
    w
}

fn encode_register() -> Vec<u8> {
    let sig = "registerModel(uint256,address,(uint16,uint16,uint16,uint16,uint16,uint16,uint32,uint32,uint32))";
    let mut v = selector(sig).to_vec();
    v.extend_from_slice(&word(MODEL_ID));
    let mut a = [0u8; 32];
    a[12..].copy_from_slice(WEIGHTS.as_slice());
    v.extend_from_slice(&a);
    // Qwen3-0.6B, truncated to what fits the registry's widths. Only the shape matters to
    // this test; the flags ride along to prove they survive a round trip.
    for f in [1024u64, 3072, 28, 16, 8, 4096, 151_936, 1_000_000, 0] {
        v.extend_from_slice(&word(f));
    }
    v
}

fn encode_project(rows: u32, cols: u32, acts: &[i64]) -> Vec<u8> {
    let sig = "projectStateless(uint256,uint32,uint32,uint32,int64[])";
    let mut v = selector(sig).to_vec();
    v.extend_from_slice(&word(MODEL_ID));
    v.extend_from_slice(&word(rows as u64));
    v.extend_from_slice(&word(cols as u64));
    v.extend_from_slice(&word(0)); // offset
    v.extend_from_slice(&word(5 * 32));
    v.extend_from_slice(&word(acts.len() as u64));
    for &a in acts {
        let mut w = [0u8; 32];
        if a < 0 {
            w[..24].fill(0xff);
        }
        w[24..].copy_from_slice(&a.to_be_bytes());
        v.extend_from_slice(&w);
    }
    v
}

fn decode_int64_array(ret: &[u8]) -> Vec<i64> {
    assert!(ret.len() >= 64, "return too short");
    let len = u64::from_be_bytes(ret[56..64].try_into().unwrap()) as usize;
    (0..len)
        .map(|i| {
            let at = 64 + i * 32 + 24;
            i64::from_be_bytes(ret[at..at + 8].try_into().unwrap())
        })
        .collect()
}

/// Registers the fixture as a model and projects against it, exactly as a caller would.
fn project(f: &Fixture) -> Vec<i64> {
    let mut db = CacheDB::new(EmptyDB::default());
    db.insert_account_info(
        CALLER,
        AccountInfo {
            balance: U256::from(1u64) << 100,
            ..Default::default()
        },
    );
    db.insert_account_info(
        WEIGHTS,
        AccountInfo {
            code: Some(Bytecode::new_raw(Bytes::from(f.blob.clone()))),
            ..Default::default()
        },
    );
    db.insert_account_info(
        REGISTRY,
        AccountInfo {
            code: Some(Bytecode::new_raw(Bytes::from(runtime_code()))),
            ..Default::default()
        },
    );

    let mut nonce = 0u64;
    let mut call = |data: Vec<u8>| -> ExecutionResult {
        let out = {
            let evm = Context::mainnet().with_db(&mut db).build_mainnet();
            let mut evm = evm.with_precompiles(TensorPrecompiles::default());
            evm.transact(TxEnv {
                caller: CALLER,
                kind: TxKind::Call(REGISTRY),
                data: data.into(),
                gas_limit: 16_000_000,
                gas_price: 0,
                nonce,
                ..Default::default()
            })
            .unwrap_or_else(|e| panic!("transaction rejected: {e:?}"))
        };
        nonce += 1;
        db.commit(out.state);
        out.result
    };

    let reg = call(encode_register());
    assert!(
        reg.is_success(),
        "{}: registerModel failed: {reg:?}",
        f.name
    );

    let proj = call(encode_project(f.rows, f.cols, &f.activations));
    match &proj {
        ExecutionResult::Success { output, .. } => match output {
            Output::Call(b) => decode_int64_array(b),
            Output::Create(b, _) => decode_int64_array(b),
        },
        other => panic!("{}: projection failed: {other:?}", f.name),
    }
}

fn fixtures() -> Vec<&'static str> {
    vec!["self_attn_q_proj", "self_attn_k_proj", "mlp_gate_proj"]
}

/// Exact agreement with the independently derived integer answer.
///
/// Bit-for-bit, not within a tolerance: the whole design rests on every node computing
/// identical values, so anything less than exact here would undermine the premise.
#[test]
fn real_weights_match_the_integer_reference_exactly() {
    for name in fixtures() {
        let f = load(name);
        let got = project(&f);
        assert_eq!(
            got, f.expected,
            "{name}: chain output differs from the reference integers"
        );
    }
}

/// Agreement with what the model actually means.
///
/// This is the check the integer tests cannot make. The tolerance covers two things: the
/// int16 encoding of bf16 weights, and Q32 rounding of the accumulator. Both are tiny —
/// bf16 carries only eight mantissa bits, so int16 with a per-row scale reproduces it
/// almost exactly — but they are not zero, and pretending otherwise would be dishonest.
#[test]
fn real_weights_match_float64_truth() {
    for name in fixtures() {
        let f = load(name);
        let got = project(&f);

        let scale: f64 = f.float_reference.iter().map(|v| v.abs()).sum::<f64>() / f.rows as f64;
        let err: f64 = got
            .iter()
            .zip(&f.float_reference)
            .map(|(g, t)| ((*g as f64 / Q32) - t).abs())
            .sum::<f64>()
            / f.rows as f64;
        let rel = err / scale;

        println!("{name:24} mean relative error vs float64: {rel:.3e}");
        assert!(
            rel < 1e-4,
            "{name}: relative error {rel:.3e} is too large for an int16 encoding of bf16"
        );
    }
}

/// The fixtures must be genuine model weights rather than anything synthetic.
///
/// A row of real attention weights has a characteristic spread; a constant or zero row
/// would pass both tests above while proving nothing about real data. This checks the
/// blob's int16 values actually vary.
#[test]
fn fixtures_contain_real_weight_data() {
    for name in fixtures() {
        let f = load(name);
        let values: Vec<i16> = f.blob[f.rows as usize..]
            .chunks_exact(2)
            .map(|c| i16::from_be_bytes([c[0], c[1]]))
            .collect();

        let distinct = values
            .iter()
            .collect::<std::collections::HashSet<_>>()
            .len();
        assert!(
            distinct > values.len() / 100,
            "{name}: only {distinct} distinct values across {} weights",
            values.len()
        );
        assert!(
            values.iter().any(|&v| v < 0) && values.iter().any(|&v| v > 0),
            "{name}: weights should straddle zero"
        );
    }
}

/// Fixtures exist and are self-describing, so a missing checkpoint cannot silently reduce
/// this suite to nothing.
#[test]
fn every_fixture_is_present() {
    let dir = repo_root().join("testdata");
    assert!(Path::new(&dir).is_dir(), "testdata/ is missing");
    for name in fixtures() {
        assert!(dir.join(format!("{name}.json")).is_file(), "{name}.json");
        assert!(dir.join(format!("{name}.bin")).is_file(), "{name}.bin");
    }
}
